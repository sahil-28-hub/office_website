/* Regenerates src/data/heroIcons.js from the installed simple-icons.
   Run after a simple-icons upgrade, or after changing which tools the
   hero's orbit rings show:

     node scripts/gen-hero-icons.mjs

   Why this exists at all: simple-icons is a single ~5MB ES module.
   Importing one named export from it pulls the module into whichever
   chunk the importer lands in — tree-shaken to the icons actually
   used, but not splittable further. The hero ships in the entry
   chunk, so importing there put every brand mark on the site in front
   of first paint. Inlining these ten keeps the entry free of the
   dependency entirely, and toolIcons.js spreads them back into the
   full map so they stay defined once. */

import { writeFileSync } from 'node:fs'
import * as si from 'simple-icons'

/* keep in step with RINGS in src/components/Hero.jsx */
const SET = {
  React: si.siReact,
  Python: si.siPython,
  Docker: si.siDocker,
  Figma: si.siFigma,
  TensorFlow: si.siTensorflow,
  MongoDB: si.siMongodb,
  Kubernetes: si.siKubernetes,
  Linux: si.siLinux,
  PyTorch: si.siPytorch,
  Git: si.siGit
}

const missing = Object.entries(SET).filter(([, v]) => !v?.path)
if (missing.length) {
  console.error('simple-icons no longer exports:', missing.map(([k]) => k).join(', '))
  process.exit(1)
}

const body = Object.entries(SET)
  .map(([k, v]) => `  ${k}: { hex: '#${v.hex}', path: '${v.path.replace(/'/g, "\\'")}' },`)
  .join('\n')

writeFileSync(
  new URL('../src/data/heroIcons.js', import.meta.url),
  `/* ==================================================================
   The ten marks on the hero's orbit rings — and nothing else.

   GENERATED by scripts/gen-hero-icons.mjs. Edit that, not this.

   Inlined rather than imported from 'simple-icons' on purpose: that
   package is one ~5MB ES module, so importing a single named export
   from the hero — which ships in the entry chunk — put every brand
   mark on the site (~98KB of path data) in front of first paint, for
   ten 46px chips.

   toolIcons.js spreads HERO_ICONS into the full map, so these ten are
   still defined exactly once and the deferred Technologies and
   Capabilities sections render the same objects.
================================================================== */

export function ico(icon, hexOverride) {
  return { path: icon.path, hex: \`#\${hexOverride || icon.hex}\` }
}

export function mono(letters, hex) {
  return { mono: letters, hex }
}

/* already in the { hex, path } shape ico() produces */
export const HERO_ICONS = {
${body}
}

/* Same lettered-chip fallback as the full set, so a name typo on a
   ring degrades to initials rather than to nothing. */
export function getHeroIcon(name) {
  if (HERO_ICONS[name]) return HERO_ICONS[name]
  const letters = name.split(/\\s+/).map((w) => w[0]).join('').slice(0, 3).toUpperCase()
  return mono(letters, '#5b6482')
}
`
)

console.log(`wrote src/data/heroIcons.js — ${Object.keys(SET).length} icons inlined`)
